// Bring the drawings in from pixeldraw: export each sheet there, then write
// them into src/render/art.gen.ts as text, so the game (and the tests, in
// node) load them without fetching or decoding anything.
// Usage: node tools/import-art.ts [--no-export]
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { inflateSync } from 'node:zlib';

const SHEETS = ['gnome', 'garden-flowers', 'garden-visitor', 'garden-props', 'garden-critters', 'garden-icons', 'garden-cottage'];
const root = resolve(import.meta.dirname, '..');
const pixeldraw = resolve(root, '../pixeldraw');
const dir = resolve(root, 'art');
mkdirSync(dir, { recursive: true });

if (!process.argv.includes('--no-export'))
  for (const name of SHEETS) execFileSync('node', ['scripts/export-sprite.js', name, `--out=${dir}`], { cwd: pixeldraw, stdio: 'inherit' });

/** Decode an 8-bit RGBA PNG. */
function decodePng(buf: Buffer): { w: number; h: number; rgba: Uint8Array } {
  let at = 8;
  let w = 0, h = 0;
  const idat: Buffer[] = [];
  while (at < buf.length) {
    const len = buf.readUInt32BE(at);
    const type = buf.toString('ascii', at + 4, at + 8);
    const data = buf.subarray(at + 8, at + 8 + len);
    if (type === 'IHDR') {
      w = data.readUInt32BE(0); h = data.readUInt32BE(4);
      if (data[8] !== 8 || data[9] !== 6 || data[12] !== 0) throw new Error('only 8-bit RGBA, not interlaced');
    } else if (type === 'IDAT') idat.push(data);
    at += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const rgba = new Uint8Array(w * h * 4);
  const stride = w * 4;
  for (let y = 0; y < h; y++) {
    const filter = raw[y * (stride + 1)];
    const row = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= 4 ? rgba[y * stride + x - 4] : 0;
      const b = y > 0 ? rgba[(y - 1) * stride + x] : 0;
      const c = x >= 4 && y > 0 ? rgba[(y - 1) * stride + x - 4] : 0;
      let v = row[x];
      if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      rgba[y * stride + x] = v & 255;
    }
  }
  return { w, h, rgba };
}

// One character per colour; '.' is transparent.
const ALPHABET = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

const out: string[] = [
  '// Generated by tools/import-art.ts from the drawings in ../pixeldraw. Do not edit: run `npm run art`.',
  '',
  'export interface Sheet {',
  '  w: number;',
  '  h: number;',
  '  /** Characters per pixel: 1, or 2 when the sheet has more colours than the alphabet has letters. */',
  '  cpp: number;',
  '  /** The colours; a pixel is the index of its colour, written in base ALPHABET.length. */',
  '  pal: string[];',
  '  /** looks[look][animation] = frames, each w*h pixels, row by row; a pixel of dots is transparent. */',
  '  looks: Record<string, Record<string, string[]>>;',
  '  /** The same frames as depth maps, when the drawing has one: a digit 1 (far) to 5 (near) per pixel. */',
  '  depth?: Record<string, Record<string, string[]>>;',
  '}',
  '',
  `export const ALPHABET = '${ALPHABET}';`,
  '',
  'export const ART: Record<string, Sheet> = {',
];

for (const name of SHEETS) {
  const manifest = JSON.parse(readFileSync(`${dir}/${name}.json`, 'utf8')) as {
    width: number; height: number; depth?: string; looks: Record<string, Record<string, [number, number, number][]>>;
  };
  const png = decodePng(readFileSync(`${dir}/${name}.png`));
  // First find every colour, then write each pixel as one character, or two when there are too many for that.
  const pal: string[] = [];
  const index = new Map<string, number>();
  const cells: (number | -1)[][] = [];
  const shape: Record<string, Record<string, number[]>> = {};
  for (const [look, anims] of Object.entries(manifest.looks)) {
    shape[look] = {};
    for (const [anim, list] of Object.entries(anims)) {
      shape[look][anim] = list.map(([fx, fy]) => {
        const frame: number[] = [];
        for (let y = 0; y < manifest.height; y++)
          for (let x = 0; x < manifest.width; x++) {
            const o = ((fy + y) * png.w + fx + x) * 4;
            if (png.rgba[o + 3] < 128) { frame.push(-1); continue; }
            const hex = '#' + [png.rgba[o], png.rgba[o + 1], png.rgba[o + 2]].map((v) => v.toString(16).padStart(2, '0')).join('');
            let i = index.get(hex);
            if (i === undefined) { i = pal.length; pal.push(hex); index.set(hex, i); }
            frame.push(i);
          }
        cells.push(frame);
        return cells.length - 1;
      });
    }
  }
  const A = ALPHABET.length;
  const cpp = pal.length <= A ? 1 : 2;
  if (pal.length > A * A) throw new Error(`${name} uses more than ${A * A} colours`);
  const code = (i: number) => (i < 0 ? '.'.repeat(cpp) : cpp === 1 ? ALPHABET[i] : ALPHABET[Math.floor(i / A)] + ALPHABET[i % A]);
  const looks: Record<string, Record<string, string[]>> = {};
  for (const look in shape) {
    looks[look] = {};
    for (const anim in shape[look]) looks[look][anim] = shape[look][anim].map((k) => cells[k].map(code).join(''));
  }
  const frames = cells.length;

  // The depth map, when the drawing has one: per pixel how near it is, 1 (far) to 5 (near). The light uses it to
  // find the edges of things and which way they face.
  let depth: Record<string, Record<string, string[]>> | undefined;
  if (manifest.depth) {
    const dpng = decodePng(readFileSync(`${dir}/${manifest.depth}`));
    const TONES = [[0x2b, 0x30, 0x48], [0x3f, 0x4a, 0x68], [0x5a, 0x69, 0x88], [0x7d, 0x90, 0xab], [0xa6, 0xbc, 0xcf]];
    depth = {};
    for (const [look, anims] of Object.entries(manifest.looks)) {
      depth[look] = {};
      for (const [anim, list] of Object.entries(anims)) {
        depth[look][anim] = list.map(([fx, fy]) => {
          let out = '';
          for (let y = 0; y < manifest.height; y++)
            for (let x = 0; x < manifest.width; x++) {
              const o = ((fy + y) * dpng.w + fx + x) * 4;
              if (dpng.rgba[o + 3] < 128) { out += '.'; continue; }
              let best = 0, bestD = Infinity;
              TONES.forEach((t, k) => {
                const d = Math.abs(dpng.rgba[o] - t[0]) + Math.abs(dpng.rgba[o + 1] - t[1]) + Math.abs(dpng.rgba[o + 2] - t[2]);
                if (d < bestD) { bestD = d; best = k; }
              });
              out += String(best + 1);
            }
          return out;
        });
      }
    }
  }
  out.push(`  ${JSON.stringify(name)}: ${JSON.stringify({ w: manifest.width, h: manifest.height, cpp, pal, looks, ...(depth && { depth }) })},`);
  console.log(`${name}: ${frames} frames, ${pal.length} colours`);
}
out.push('};', '');
writeFileSync(resolve(root, 'src/render/art.gen.ts'), out.join('\n'));
console.log('wrote src/render/art.gen.ts');
