// Build the drawings into the game: each one in art/ (its text, as it is drawn)
// is rendered to a sprite sheet and written into src/render/art.gen.ts as text,
// so the game (and the tests, in node) load them without fetching or decoding
// anything. Run by the engine whenever a drawing changes.
// Usage: node tools/import-art.ts [--from=<folder with art/ and depth/>] [--out=<file>]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { spriteSheet } from '../../../art/sprites.ts';

// The drawings the game is made of, in the order they have always been built; a new one comes after them.
const KNOWN = ['gnome', 'garden-flowers', 'garden-visitor', 'garden-props', 'garden-critters', 'garden-icons', 'garden-cottage'];
const root = resolve(import.meta.dirname, '..');
const arg = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const from = resolve(arg('from') ?? root);
const outFile = resolve(arg('out') ?? `${root}/src/render/art.gen.ts`);
const found = readdirSync(`${from}/art`).filter((f) => f.endsWith('.txt')).map((f) => f.slice(0, -4)).sort();
const SHEETS = [...KNOWN.filter((n) => found.includes(n)), ...found.filter((n) => !KNOWN.includes(n))];

// One character per colour; '.' is transparent.
const ALPHABET = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

const out: string[] = [
  '// Generated by tools/import-art.ts from the drawings in art/. Do not edit: change a drawing, or run `npm run art`.',
  '',
  'export interface Sheet {',
  '  w: number;',
  '  h: number;',
  '  /** Characters per pixel: 1, or 2 when the sheet has more colours than the alphabet has letters. */',
  '  cpp: number;',
  '  /** The colours; a pixel is the index of its colour, written in base ALPHABET.length. */',
  '  pal: string[];',
  '  /** looks[look][animation] = frames, each w*h pixels, row by row; a pixel of dots is transparent. */',
  '  looks: Record<string, Record<string, string[]>>;',
  '  /** The same frames as depth maps, when the drawing has one: a digit 1 (far) to 5 (near) per pixel. */',
  '  depth?: Record<string, Record<string, string[]>>;',
  '}',
  '',
  `export const ALPHABET = '${ALPHABET}';`,
  '',
  'export const ART: Record<string, Sheet> = {',
];

for (const name of SHEETS) {
  const depthFile = `${from}/depth/${name}.txt`;
  const sheet = spriteSheet(name, readFileSync(`${from}/art/${name}.txt`, 'utf8'), existsSync(depthFile) ? readFileSync(depthFile, 'utf8') : undefined);
  const manifest = { width: sheet.width, height: sheet.height, looks: sheet.looks, depth: sheet.depthRgba };
  const png = { w: sheet.sheetW, rgba: sheet.rgba };
  // First find every colour, then write each pixel as one character, or two when there are too many for that.
  const pal: string[] = [];
  const index = new Map<string, number>();
  const cells: (number | -1)[][] = [];
  const shape: Record<string, Record<string, number[]>> = {};
  for (const [look, anims] of Object.entries(manifest.looks)) {
    shape[look] = {};
    for (const [anim, list] of Object.entries(anims)) {
      shape[look][anim] = list.map(([fx, fy]) => {
        const frame: number[] = [];
        for (let y = 0; y < manifest.height; y++)
          for (let x = 0; x < manifest.width; x++) {
            const o = ((fy + y) * png.w + fx + x) * 4;
            if (png.rgba[o + 3] < 128) { frame.push(-1); continue; }
            const hex = '#' + [png.rgba[o], png.rgba[o + 1], png.rgba[o + 2]].map((v) => v.toString(16).padStart(2, '0')).join('');
            let i = index.get(hex);
            if (i === undefined) { i = pal.length; pal.push(hex); index.set(hex, i); }
            frame.push(i);
          }
        cells.push(frame);
        return cells.length - 1;
      });
    }
  }
  const A = ALPHABET.length;
  const cpp = pal.length <= A ? 1 : 2;
  if (pal.length > A * A) throw new Error(`${name} uses more than ${A * A} colours`);
  const code = (i: number) => (i < 0 ? '.'.repeat(cpp) : cpp === 1 ? ALPHABET[i] : ALPHABET[Math.floor(i / A)] + ALPHABET[i % A]);
  const looks: Record<string, Record<string, string[]>> = {};
  for (const look in shape) {
    looks[look] = {};
    for (const anim in shape[look]) looks[look][anim] = shape[look][anim].map((k) => cells[k].map(code).join(''));
  }
  const frames = cells.length;

  // The depth map, when the drawing has one: per pixel how near it is, 1 (far) to 5 (near). The light uses it to
  // find the edges of things and which way they face.
  let depth: Record<string, Record<string, string[]>> | undefined;
  if (manifest.depth) {
    const dpng = { w: sheet.sheetW, rgba: manifest.depth };
    const TONES = [[0x2b, 0x30, 0x48], [0x3f, 0x4a, 0x68], [0x5a, 0x69, 0x88], [0x7d, 0x90, 0xab], [0xa6, 0xbc, 0xcf]];
    depth = {};
    for (const [look, anims] of Object.entries(manifest.looks)) {
      depth[look] = {};
      for (const [anim, list] of Object.entries(anims)) {
        depth[look][anim] = list.map(([fx, fy]) => {
          let out = '';
          for (let y = 0; y < manifest.height; y++)
            for (let x = 0; x < manifest.width; x++) {
              const o = ((fy + y) * dpng.w + fx + x) * 4;
              if (dpng.rgba[o + 3] < 128) { out += '.'; continue; }
              let best = 0, bestD = Infinity;
              TONES.forEach((t, k) => {
                const d = Math.abs(dpng.rgba[o] - t[0]) + Math.abs(dpng.rgba[o + 1] - t[1]) + Math.abs(dpng.rgba[o + 2] - t[2]);
                if (d < bestD) { bestD = d; best = k; }
              });
              out += String(best + 1);
            }
          return out;
        });
      }
    }
  }
  out.push(`  ${JSON.stringify(name)}: ${JSON.stringify({ w: manifest.width, h: manifest.height, cpp, pal, looks, ...(depth && { depth }) })},`);
  console.log(`${name}: ${frames} frames, ${pal.length} colours`);
}
out.push('};', '');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out.join('\n'));
console.log(`wrote ${outFile}`);
